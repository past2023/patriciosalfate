let lang = 'ru';

/* Default language is RU. EN only when the user chooses it
   (button / ?lang=en) — the choice is remembered. */
export function detectLang() {
  try {
    const p = new URLSearchParams(location.search).get('lang');
    if (p === 'ru' || p === 'en') return p;
    const s = localStorage.getItem('ps.lang');
    if (s === 'ru' || s === 'en') return s;
  } catch (_) {}
  return 'ru';
}

export function getLang() { return lang; }

export function t(key) {
  return (DICT[lang] && DICT[lang][key]) ?? DICT.ru[key] ?? key;
}

/* plural: RU (one/few/many), EN (one/many) */
export function plural(n, forms) {
  if (lang === 'ru') {
    const m10 = n % 10, m100 = n % 100;
    if (m10 === 1 && m100 !== 11) return forms[0];
    if (m10 >= 2 && m10 <= 4 && (m100 < 10 || m100 >= 20)) return forms[1];
    return forms[2];
  }
  return n === 1 ? forms[0] : forms[forms.length - 1];
}

export function fmtDate(ms) {
  if (!ms) return '';
  return new Intl.DateTimeFormat(lang === 'ru' ? 'ru-RU' : 'en-GB',
    { day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(ms));
}

export function applyLang() {
  document.documentElement.lang = lang;
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => { el.setAttribute('aria-label', t(el.dataset.i18nAria)); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.setAttribute('title', t(el.dataset.i18nTitle)); });
  /* sub-pages can define their own title/description via data-i18n */
  const titleEl = document.querySelector('title[data-i18n]');
  const titleKey = titleEl ? titleEl.dataset.i18n : 'meta.title';
  document.title = t(titleKey);
  const desc = document.querySelector('meta[name="description"]');
  const descKey = desc && desc.dataset.i18n ? desc.dataset.i18n : 'meta.desc';
  if (desc) desc.content = t(descKey);
  const ogT = document.querySelector('meta[property="og:title"]');
  if (ogT) ogT.content = t(titleKey);
  const ogD = document.querySelector('meta[property="og:description"]');
  if (ogD) ogD.content = t(descKey);
}

export function setLang(l, { push = true } = {}) {
  lang = l;
  try { localStorage.setItem('ps.lang', l); } catch (_) {}
  applyLang();
  if (push) {
    try {
      const url = new URL(location.href);
      url.searchParams.set('lang', l);
      history.replaceState(null, '', url);
    } catch (_) {}
  }
  bus.emit('lang', l);
}
